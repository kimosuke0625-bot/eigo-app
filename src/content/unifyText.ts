/**
 * 見た目は同じでも中身の文字が違うものを、同じ文字にそろえる（答え合わせ・ディクテーションの採点で使う）。
 * 2026-10-14 利用者の指摘「表記が一緒なのに間違いとされる」への対応。iPhone で起きやすいもの：
 * - 日本語キーボードのまま打った全角の英数字・記号・空白（Ｉ ． ？ ＇ 全角スペースなど）→ NFKC で半角に
 * - 自動修正や貼り付けで混ざる見えない文字（幅ゼロの空白など）→ 消す
 * - アポストロフィ・引用符・ハイフン・ダッシュ・三点リーダーの種類の違い → 1種類に
 * - 改行しない空白（NBSP）など特別な空白 → ふつうの空白に
 */
export function unifyText(s: string): string {
  return s
    .normalize('NFKC')
    .replace(/[​-‍⁠﻿­]/g, '')
    .replace(/[‘’‚‛ʼʹ`´′‵]/g, "'")
    .replace(/[“”„‟″‶«»]/g, '"')
    .replace(/[‐‑‒–—―−]/g, '-')
    .replace(/…/g, '...')
    .replace(/[  -   　]/g, ' ')
}
